/**
 * 4. Gross Profit & FIFO COGS Report PDF Export
 */
export function exportGrossProfitReportPdf(
  meta: RestaurantMeta,
  dates: DateRangeMeta,
  dailyProfits: any[]
) {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
  let startY = drawReportHeader(doc, 'FIFO Gross Profit & COGS Report', meta, dates);

  const totalNetSales = dailyProfits.reduce((sum, d) => sum + Number(d.net_sales || 0), 0);
  const totalFifoCogs = dailyProfits.reduce((sum, d) => sum + Number(d.fifo_cogs || 0), 0);
  const totalGrossProfit = totalNetSales - totalFifoCogs;
  const overallMargin = totalNetSales > 0 ? ((totalGrossProfit / totalNetSales) * 100).toFixed(1) : '0';
  const sym = meta.currencySymbol || 'Rs.';

  // Summary Box
  doc.setFillColor(248, 250, 252);
  doc.roundedRect(14, startY, doc.internal.pageSize.width - 28, 18, 2, 2, 'F');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8.5);
  doc.setTextColor(15, 23, 42);

  doc.text(`Total Net Sales: ${sym} ${totalNetSales.toLocaleString()}`, 18, startY + 7);
  doc.text(`FIFO COGS: ${sym} ${totalFifoCogs.toLocaleString()}`, 74, startY + 7);
  doc.setTextColor(16, 185, 129);
  doc.text(`Gross Profit: ${sym} ${totalGrossProfit.toLocaleString()}`, 130, startY + 7);
  doc.setTextColor(15, 23, 42);
  doc.text(`Avg Margin: ${overallMargin}%`, 18, startY + 14);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7.5);
  doc.setTextColor(100, 116, 139);
  doc.text('Note: COGS reflects exact FIFO batch acquisition cost of consumed ingredients.', 74, startY + 14);

  startY += 24;

  const tableRows = dailyProfits.map((d) => [
    new Date(d.report_date).toLocaleDateString('en-US', {
      weekday: 'short',
      month: 'short',
      day: 'numeric',
      year: 'numeric',
    }),
    d.order_count,
    `${sym} ${Number(d.net_sales || 0).toLocaleString()}`,
    `${sym} ${Number(d.fifo_cogs || 0).toLocaleString()}`,
    `${sym} ${Number(d.gross_profit || 0).toLocaleString()}`,
    `${d.gross_margin_percent || 0}%`,
  ]);

  autoTable(doc, {
    startY,
    head: [[
      'Date',
      'Completed Orders',
      'Net Sales',
      'FIFO COGS',
      'Gross Profit',
      'Gross Margin',
    ]],
    body: tableRows,
    styles: {
      fontSize: 8.5,
      cellPadding: 3,
      overflow: 'linebreak',
    },
    headStyles: {
      fillColor: [15, 23, 42],
      textColor: 255,
      fontStyle: 'bold',
    },
    columnStyles: {
      0: { cellWidth: 46 },
      1: { cellWidth: 26, halign: 'center' },
      2: { cellWidth: 32, halign: 'right' },
      3: { cellWidth: 32, halign: 'right' },
      4: { cellWidth: 32, halign: 'right', fontStyle: 'bold' },
      5: { cellWidth: 24, halign: 'center', fontStyle: 'bold' },
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252],
    },
    margin: { left: 14, right: 14 },
  });

  attachFooter(doc);
  doc.save(`FIFO_Gross_Profit_Report_${dates.startDate}_${dates.endDate}.pdf`);
}

/**
 * 5. Net Profit (Full P&L) PDF Export
 */
export function exportNetProfitReportPdf(
  meta: RestaurantMeta,
  dates: DateRangeMeta,
  summary: any
) {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
  let startY = drawReportHeader(doc, 'Comprehensive Profit & Loss (P&L)', meta, dates);

  const sym = meta.currencySymbol || 'Rs.';

  const netSales = Number(summary?.netSales || 0);
  const cogs = Number(summary?.costOfGoodsSold || 0);
  const grossProfit = Number(summary?.grossProfit || 0);
  const totalExpenses = Number(summary?.totalExpenses || 0);
  const operatingProfit = Number(summary?.operatingProfit || 0);
  const discounts = Number(summary?.discounts || 0);
  const taxCollected = Number(summary?.taxCollected || 0);
  const serviceCharges = Number(summary?.serviceCharges || 0);

  const plRows = [
    ['Gross Revenue / Sales', `${sym} ${Number(summary?.grossSales || 0).toLocaleString()}`, 'Total order volume before reductions'],
    ['Discounts Allowed (-)', `(${sym} ${discounts.toLocaleString()})`, 'Promotional and cashier discounts'],
    ['Net Sales Revenue', `${sym} ${netSales.toLocaleString()}`, 'Net recognized revenue from restaurant operations'],
    ['Cost of Goods Sold (COGS) (-)', `(${sym} ${cogs.toLocaleString()})`, 'FIFO acquisition cost of raw recipe ingredients'],
    ['Gross Operating Profit', `${sym} ${grossProfit.toLocaleString()}`, `${summary?.grossMarginPercent || 0}% Gross Margin on Sales`],
    ['Operating Expenses (OPEX) (-)', `(${sym} ${totalExpenses.toLocaleString()})`, 'Rent, utilities, staff salaries, repairs, and supplies'],
    ['Net Operating Profit (EBIT)', `${sym} ${operatingProfit.toLocaleString()}`, `${summary?.operatingMarginPercent || 0}% Net Operating Margin`],
    ['Sales Tax Collected (Liability)', `${sym} ${taxCollected.toLocaleString()}`, 'Collected on behalf of state tax authority'],
    ['Service Charges Collected', `${sym} ${serviceCharges.toLocaleString()}`, 'Staff gratuity / restaurant service fees'],
  ];

  autoTable(doc, {
    startY,
    head: [['Financial Line Item', 'Amount', 'Accounting Description']],
    body: plRows,
    styles: {
      fontSize: 9,
      cellPadding: 4,
      overflow: 'linebreak',
    },
    headStyles: {
      fillColor: [15, 23, 42],
      textColor: 255,
      fontStyle: 'bold',
    },
    columnStyles: {
      0: { cellWidth: 65, fontStyle: 'bold' },
      1: { cellWidth: 45, halign: 'right', fontStyle: 'bold' },
      2: { cellWidth: 72, textColor: [100, 116, 139] },
    },
    didParseCell: (data) => {
      // Highlight profit rows
      if (data.row.index === 2 || data.row.index === 4) {
        data.cell.styles.fillColor = [241, 245, 249]; // light gray
      }
      if (data.row.index === 6) {
        data.cell.styles.fillColor = operatingProfit >= 0 ? [236, 253, 245] : [254, 242, 242];
        if (data.column.index === 1) {
          data.cell.styles.textColor = operatingProfit >= 0 ? [5, 150, 105] : [220, 38, 38];
        }
      }
    },
    margin: { left: 14, right: 14 },
  });

  attachFooter(doc);
  doc.save(`Net_Profit_PL_Report_${dates.startDate}_${dates.endDate}.pdf`);
}


/**
 * 6. Bill-Wise Profit and Loss PDF Export
 */
export function exportBillWiseProfitLossPdf(
  meta: RestaurantMeta,
  dates: DateRangeMeta,
  summary: any,
  bills: any[]
) {
  const doc = new jsPDF({ orientation: 'landscape', unit: 'mm', format: 'a4' });
  const sym = meta.currencySymbol || 'Rs.';

  let startY = drawReportHeader(doc, 'Bill-Wise Profit & Loss Audit Report', meta, dates);

  // Executive Summary KPI Banner
  doc.setFillColor(241, 245, 249); // slate-100
  doc.roundedRect(14, startY, doc.internal.pageSize.width - 28, 16, 2, 2, 'F');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8.5);
  doc.setTextColor(15, 23, 42); // slate-900

  const totalBills = summary?.totalBills || bills.length;
  const netSales = Number(summary?.totalNetSales || 0);
  const fifoCogs = Number(summary?.totalCogs || 0);
  const grossProfit = Number(summary?.totalGrossProfit || 0);
  const avgMargin = Number(summary?.averageMarginPercent || 0);
  const avgProfit = Number(summary?.averageProfitPerBill || 0);

  doc.text(`Total Bills: ${totalBills}`, 20, startY + 6);
  doc.text(`Net Food Sales: ${sym} ${netSales.toLocaleString()}`, 65, startY + 6);
  doc.text(`FIFO COGS: ${sym} ${fifoCogs.toLocaleString()}`, 125, startY + 6);
  
  if (grossProfit >= 0) {
    doc.setTextColor(22, 163, 74); // green
  } else {
    doc.setTextColor(220, 38, 38); // red
  }
  doc.text(`Gross Profit: ${sym} ${grossProfit.toLocaleString()}`, 180, startY + 6);

  doc.setTextColor(15, 23, 42);
  doc.text(`Overall Margin: ${avgMargin.toFixed(1)}%`, 20, startY + 12);
  doc.text(`Avg Profit/Bill: ${sym} ${avgProfit.toLocaleString()}`, 65, startY + 12);
  doc.text(`Profitable Bills: ${summary?.profitableBillsCount || 0} / ${totalBills}`, 125, startY + 12);

  startY += 22;

  const tableRows = bills.map((b) => {
    const dt = new Date(b.createdAt);
    const dateFormatted = dt.toLocaleDateString('en-US', { month: 'short', day: 'numeric' }) + ' ' + dt.toLocaleTimeString('en-US', { hour: '2-digit', minute: '2-digit' });
    const profitVal = Number(b.grossProfit || 0);
    const marginVal = Number(b.grossMarginPercent || 0);

    return [
      b.orderNumber,
      dateFormatted,
      b.orderType,
      b.customerName || (b.orderType === 'DELIVERY' ? 'Delivery Guest' : 'Walk-in Guest'),
      `${sym} ${Number(b.subtotal || 0).toLocaleString()}`,
      `${sym} ${Number(b.totalDiscount || 0).toLocaleString()}`,
      `${sym} ${Number(b.netSales || 0).toLocaleString()}`,
      `${sym} ${Number(b.fifoCogs || 0).toLocaleString()}`,
      `${sym} ${profitVal.toLocaleString()}`,
      `${marginVal.toFixed(1)}%`,
      `${sym} ${Number(b.grandTotal || 0).toLocaleString()}`,
      b.paymentMethods || 'CASH',
    ];
  });

  autoTable(doc, {
    startY,
    head: [[
      'Bill #',
      'Date & Time',
      'Channel',
      'Customer',
      'Subtotal',
      'Discount',
      'Net Sales',
      'FIFO COGS',
      'Gross Profit',
      'Margin %',
      'Grand Total',
      'Payment',
    ]],
    body: tableRows,
    styles: {
      fontSize: 7.5,
      cellPadding: 2,
      overflow: 'linebreak',
    },
    headStyles: {
      fillColor: [15, 23, 42],
      textColor: 255,
      fontStyle: 'bold',
    },
    columnStyles: {
      0: { cellWidth: 24, fontStyle: 'bold' },
      1: { cellWidth: 26 },
      2: { cellWidth: 20 },
      3: { cellWidth: 32 },
      4: { cellWidth: 20, halign: 'right' },
      5: { cellWidth: 18, halign: 'right' },
      6: { cellWidth: 22, halign: 'right', fontStyle: 'bold' },
      7: { cellWidth: 22, halign: 'right' },
      8: { cellWidth: 24, halign: 'right', fontStyle: 'bold' },
      9: { cellWidth: 18, halign: 'center' },
      10: { cellWidth: 22, halign: 'right' },
      11: { cellWidth: 22, halign: 'center' },
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252],
    },
    margin: { left: 14, right: 14 },
    didParseCell: function(data) {
      if (data.section === 'body' && data.column.index === 8) {
        const raw = String(data.cell.raw);
        if (raw.includes('-')) {
          data.cell.styles.textColor = [220, 38, 38];
        } else {
          data.cell.styles.textColor = [22, 163, 74];
        }
      }
    }
  });

  attachFooter(doc);
  doc.save(`Bill_Wise_Profit_Loss_${dates.startDate}_${dates.endDate}.pdf`);
}
