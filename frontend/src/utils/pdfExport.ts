/**
 * Helper to open an in-memory jsPDF document directly in the browser's PDF print viewer
 */
export function openPdfForPrint(doc: jsPDF) {
  const blobUrl = doc.output('bloburl');
  const printWin = window.open(blobUrl, '_blank');
  if (printWin) {
    printWin.focus();
  }
}

