import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';

interface RestaurantMeta {
  name: string;
  currency?: string;
  currencySymbol?: string;
  branch?: string;
}

interface DateRangeMeta {
  startDate: string;
  endDate: string;
}

function drawReportHeader(
  doc: jsPDF,
  title: string,
  meta: RestaurantMeta,
  dates: DateRangeMeta
) {
  // Brand Header
  doc.setFillColor(15, 23, 42); // slate-900
  doc.rect(0, 0, doc.internal.pageSize.width, 28, 'F');

  // Restaurant Name
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.setTextColor(255, 255, 255);
  doc.text(meta.name || 'Restaurant POS SaaS', 14, 12);

  // Branch / Tagline
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(148, 163, 184); // slate-400
  doc.text(meta.branch ? `Branch: ${meta.branch}` : 'Multi-Tenant Restaurant SaaS Platform', 14, 20);

  // Title on right
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(249, 115, 22); // brand orange
  doc.text(title.toUpperCase(), doc.internal.pageSize.width - 14, 14, { align: 'right' });

  // Date Range on right
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(203, 213, 225); // slate-300
  doc.text(
    `Period: ${dates.startDate} to ${dates.endDate}`,
    doc.internal.pageSize.width - 14,
    21,
    { align: 'right' }
  );

  // Return Y cursor position
  return 36;
}

function attachFooter(doc: jsPDF) {
  const pageCount = (doc.internal as any).getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184);
    doc.text(
      `Generated by Restaurant POS SaaS on ${new Date().toLocaleString()} | Page ${i} of ${pageCount}`,
      14,
      doc.internal.pageSize.height - 8
    );
  }
}

/**
 * 1. Sales Report PDF Export
 */
export function exportSalesReportPdf(
  meta: RestaurantMeta,
  dates: DateRangeMeta,
  sales: any[]
) {
  const doc = new jsPDF({ orientation: 'landscape', unit: 'mm', format: 'a4' });
  let startY = drawReportHeader(doc, 'Sales Detailed Report', meta, dates);

  // Calculate totals
  const totalGrand = sales.reduce((sum, s) => sum + Number(s.grand_total || 0), 0);
  const totalTax = sales.reduce((sum, s) => sum + Number(s.tax_amount || 0), 0);
  const totalDiscount = sales.reduce((sum, s) => sum + Number(s.total_discount || 0), 0);
  const sym = meta.currencySymbol || 'Rs.';

  // Summary KPI box
  doc.setFillColor(248, 250, 252);
  doc.roundedRect(14, startY, doc.internal.pageSize.width - 28, 16, 2, 2, 'F');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.setTextColor(15, 23, 42);

  doc.text(`Total Orders: ${sales.length}`, 20, startY + 10);
  doc.text(`Discounts: ${sym} ${totalDiscount.toLocaleString()}`, 80, startY + 10);
  doc.text(`Tax Liability: ${sym} ${totalTax.toLocaleString()}`, 150, startY + 10);
  doc.setTextColor(234, 88, 12);
  doc.text(`Grand Total Sales: ${sym} ${totalGrand.toLocaleString()}`, 215, startY + 10);

  startY += 22;

  const tableRows = sales.map((s) => [
    s.order_number,
    new Date(s.created_at).toLocaleString('en-US', {
      month: 'short',
      day: 'numeric',
      hour: '2-digit',
      minute: '2-digit',
    }),
    s.order_type || 'DINE_IN',
    s.customer_name || 'Walk-in',
    s.item_count || 1,
    `${sym} ${Number(s.subtotal || 0).toLocaleString()}`,
    `${sym} ${Number(s.total_discount || 0).toLocaleString()}`,
    `${sym} ${Number(s.tax_amount || 0).toLocaleString()}`,
    `${sym} ${Number(s.grand_total || 0).toLocaleString()}`,
    s.payment_methods || 'CASH',
    s.cashier_name || 'Staff',
  ]);

  autoTable(doc, {
    startY,
    head: [[
      'Order #',
      'Date/Time',
      'Type',
      'Customer',
      'Items',
      'Subtotal',
      'Discount',
      'Tax',
      'Grand Total',
      'Payment',
      'Cashier',
    ]],
    body: tableRows,
    styles: {
      fontSize: 8,
      cellPadding: 2.5,
      overflow: 'linebreak',
    },
    headStyles: {
      fillColor: [15, 23, 42],
      textColor: 255,
      fontStyle: 'bold',
      halign: 'left',
    },
    columnStyles: {
      0: { cellWidth: 26, fontStyle: 'bold' },
      1: { cellWidth: 28 },
      2: { cellWidth: 22 },
      3: { cellWidth: 28 },
      4: { cellWidth: 14, halign: 'center' },
      5: { cellWidth: 24, halign: 'right' },
      6: { cellWidth: 22, halign: 'right' },
      7: { cellWidth: 22, halign: 'right' },
      8: { cellWidth: 28, halign: 'right', fontStyle: 'bold' },
      9: { cellWidth: 25 },
      10: { cellWidth: 28 },
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252],
    },
    margin: { left: 14, right: 14 },
  });

  attachFooter(doc);
  doc.save(`Sales_Report_${dates.startDate}_${dates.endDate}.pdf`);
}

